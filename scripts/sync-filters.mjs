import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const css = (await readFile(new URL("filters/mister.css", root), "utf8")).trim();
const hosts = JSON.parse(await readFile(new URL("filters/ad-hosts.json", root), "utf8"));

const injection = `(() => {
  const id = "mister-clean-native-styles";
  let style = document.getElementById(id);
  if (!style) {
    style = document.createElement("style");
    style.id = id;
    (document.head || document.documentElement).appendChild(style);
  }
  style.textContent = ${JSON.stringify(css)};

  if (!window.__misterCleanGoogleGuard) {
    window.__misterCleanGoogleGuard = true;
    document.addEventListener("click", event => {
      const control = event.target instanceof Element
        ? event.target.closest("button, a, [role='button']")
        : null;
      if (!control) return;

      const label = [
        control.textContent,
        control.getAttribute("aria-label"),
        control.getAttribute("title")
      ].filter(Boolean).join(" ").toLowerCase();

      if (!label.includes("google")) return;

      event.preventDefault();
      event.stopPropagation();
      event.stopImmediatePropagation();
      window.alert(
        "El acceso con Google no puede completarse dentro de Mister Clean porque Google y Android no comparten la sesión del navegador con esta app. Usa otro método de acceso de Mister. Si tu cuenta solo tiene Google, tendrás que abrir Mister directamente en el navegador."
      );
    }, true);
  }
})();`;

const escapedHosts = hosts.map(host => host.replaceAll(".", "\\."));
const contentRules = JSON.stringify([{
  trigger: { "url-filter": `^https?://([^/]+\\.)?(${escapedHosts.join("|")})(/|$)` },
  action: { type: "block" }
}]);

const swift = `// Generated by scripts/sync-filters.mjs. Do not edit directly.
import Foundation

enum GeneratedFilters {
    static let cssInjectionJavaScript = ${JSON.stringify(injection)}
    static let contentRuleJSON = ${JSON.stringify(contentRules)}
}
`;

const javaHosts = hosts.map(host => `        "${host}"`).join(",\n");
const java = `// Generated by scripts/sync-filters.mjs. Do not edit directly.
package dev.raulcano.misterclean;

import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

final class GeneratedFilters {
    static final String CSS_INJECTION_JAVASCRIPT = ${JSON.stringify(injection)};
    static final Set<String> AD_HOSTS = new HashSet<>(Arrays.asList(
${javaHosts}
    ));

    private GeneratedFilters() {}
}
`;

await Promise.all([
  writeFile(new URL("ios/App/App/GeneratedFilters.swift", root), swift),
  writeFile(new URL("android/app/src/main/java/dev/raulcano/misterclean/GeneratedFilters.java", root), java)
]);
